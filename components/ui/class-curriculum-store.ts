export function getResourcesByClass(classKey: ClassCategoryKey): {
  courses: ClassResourceItem[];
  books: ClassResourceItem[];
  ebooks: ClassResourceItem[];
  freeItems: ClassResourceItem[];
  all: ClassResourceItem[];
} {
  const all = ALL_CLASS_RESOURCES.filter((r) => r.classKey === classKey);
  return {
    courses: all.filter((r) => r.type === "course"),
    books: all.filter((r) => r.type === "book"),
    ebooks: all.filter((r) => r.type === "ebook"),
    freeItems: all.filter((r) => r.type === "free" || r.isFree === true),
    all,
  };
}

export function getClassDefinition(key: ClassCategoryKey): ClassDefinition {
  return (
    CLASS_DEFINITIONS.find((c) => c.key === key) ||
    CLASS_DEFINITIONS[0] // fallback SSC
  );
}
